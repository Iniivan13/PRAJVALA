const MONTHS = ["Jan", "Feb", "Mar", "Apr", "Mei", "Jun", "Jul", "Agu", "Sep", "Okt", "Nov"];

const PLAN_WEIGHTS = [4, 5, 6, 7, 9, 10, 10, 11, 12, 13, 13];
const REAL_WEIGHTS = [3, 4, 5, 6, 8, 9, 10, 11, 12, 15, 17];

const roundToMillion = (value: number) => Math.round(value / 1_000_000) * 1_000_000;

function buildCashflow(total: number, absorbed: number): CashflowPoint[] {
  const planned: number[] = [];
  const realized: number[] = [];
  let plannedSum = 0;
  let realizedSum = 0;

  MONTHS.forEach((_, index) => {
    if (index === MONTHS.length - 1) {
      planned.push(total - plannedSum);
      realized.push(absorbed - realizedSum);
      return;
    }
    const plan = roundToMillion((total * PLAN_WEIGHTS[index]) / 100);
    const real = roundToMillion((absorbed * REAL_WEIGHTS[index]) / 100);
    planned.push(plan);
    realized.push(real);
    plannedSum += plan;
    realizedSum += real;
  });

  return MONTHS.map((month, index) => ({
    month,
    planned: planned[index],
    realized: realized[index],
  }));
}

