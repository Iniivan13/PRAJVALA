export function getRegion(regionId: string): Region | undefined {
  return REGIONS.find((region) => region.id === regionId);
}

export function getProject(projectId: string): Project | undefined {
  return PROJECTS.find((project) => project.id === projectId);
}

export function getProjectsForRegion(regionId: string | "all"): Project[] {
  if (regionId === "all") return PROJECTS;
  return PROJECTS.filter((project) => project.regionId === regionId);
}

export function getBudgetItems(regionId: string | "all"): BudgetItem[] {
  if (regionId === "all") return BUDGET_ITEMS;
  return BUDGET_ITEMS.filter((item) => item.regionId === regionId);
}

export function getReportsForProject(projectId: string): CitizenReport[] {
  return CITIZEN_REPORTS.filter((report) => report.projectId === projectId);
}

export function getDocumentsForRegion(regionId: string | "all"): PublicDocument[] {
  if (regionId === "all") return PUBLIC_DOCUMENTS;
  return PUBLIC_DOCUMENTS.filter((document) => document.regionId === regionId);
}

export function getRegionSummary(regionId: string | "all"): RegionSummary {
  if (regionId === "all") {
    const totalBudget = REGIONS.reduce((sum, region) => sum + region.totalBudget, 0);
    const absorbed = REGIONS.reduce((sum, region) => sum + region.absorbed, 0);
    const accountabilityScore = Math.round(
      (REGIONS.reduce(
        (sum, region) => sum + region.accountabilityScore * region.totalBudget,
        0,
      ) /
        totalBudget) *
        10,
    ) / 10;

    const sectorMap = new Map<string, SectorAllocation>();

    REGIONS.forEach((region) => {
      region.sectors.forEach((sector) => {
        const existing = sectorMap.get(sector.sector);
        if (existing) {
          existing.pagu += sector.pagu;
          existing.realized += sector.realized;
        } else {
          sectorMap.set(sector.sector, { ...sector });
        }
      });
    });

    const cashflow: CashflowPoint[] = MONTHS.map((month, index) => ({
      month,
      planned: REGIONS.reduce((sum, region) => sum + (region.cashflow[index]?.planned ?? 0), 0),
      realized: REGIONS.reduce((sum, region) => sum + (region.cashflow[index]?.realized ?? 0), 0),
    }));

    return {
      id: "all",
      name: "Semua Wilayah",
      level: "Nasional",
      population: REGIONS.reduce((sum, region) => sum + region.population, 0),
      totalBudget,
      absorbed,
      absorptionRate: Math.round((absorbed / totalBudget) * 1000) / 10,
      accountabilityScore,
      verifiedProjects: PROJECTS.filter((project) => project.validationScore >= 85).length,
      totalProjects: PROJECTS.length,
      sectors: Array.from(sectorMap.values()),
      cashflow,
    };
  }

  const region = getRegion(regionId) ?? REGIONS[0];
  return {
    id: region.id,
    name: region.name,
    level: region.level,
    population: region.population,
    totalBudget: region.totalBudget,
    absorbed: region.absorbed,
    absorptionRate: Math.round((region.absorbed / region.totalBudget) * 1000) / 10,
    accountabilityScore: region.accountabilityScore,
    verifiedProjects: getProjectsForRegion(region.id).filter(
      (project) => project.validationScore >= 85,
    ).length,
    totalProjects: getProjectsForRegion(region.id).length,
    sectors: region.sectors,
    cashflow: region.cashflow,
  };
}

